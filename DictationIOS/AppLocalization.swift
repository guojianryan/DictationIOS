@MainActor
final class AppLocalization: ObservableObject {
    static let choices: [(id: String, title: String)] = [
        ("en", "English"),
        ("de", "Deutsch"),
        ("es", "Español"),
        ("fr", "Français"),
        ("it", "Italiano"),
        ("ja", "日本語"),
        ("zh", "中文")
    ]

    private static let storageKey = "appLanguage"

    @Published var appLanguage: String {
        didSet {
            guard oldValue != appLanguage else { return }
            UserDefaults.standard.set(appLanguage, forKey: Self.storageKey)
        }
    }

    init() {
        let stored = UserDefaults.standard.string(forKey: Self.storageKey) ?? "system"
        if stored == "system" || LocalizationTable.supportedCodes.contains(stored) {
            appLanguage = stored
        } else {
            appLanguage = "system"
        }
    }

    var resolvedCode: String {
        LocalizationTable.resolvedCode(preference: appLanguage)
    }

    func string(_ text: LocalizableText) -> String {
        LocalizationTable.string(text, languageCode: resolvedCode)
    }

    func languageName(for identifier: String) -> String {
        LocalizationTable.languageName(for: identifier, displayLanguage: resolvedCode)
    }
}
