import Combine
import Foundation

enum LocalizableArgument: Equatable {
    case text(String)
    case language(String)
}

struct LocalizableText: Equatable, ExpressibleByStringLiteral {
    var key: String
    var arguments: [LocalizableArgument]
    var verbatim: String?

    var isEmpty: Bool {
        if let verbatim {
            return verbatim.isEmpty
        }
        return key.isEmpty
    }

    init(key: String, arguments: [LocalizableArgument] = [], verbatim: String? = nil) {
        self.key = key
        self.arguments = arguments
        self.verbatim = verbatim
    }

    init(stringLiteral value: String) {
        key = value
        arguments = []
        verbatim = nil
    }

    static func format(_ key: String, _ arguments: String...) -> LocalizableText {
        LocalizableText(key: key, arguments: arguments.map(LocalizableArgument.text))
    }

    static func language(_ key: String, _ identifier: String) -> LocalizableText {
        LocalizableText(key: key, arguments: [.language(identifier)])
    }

    static func verbatim(_ text: String) -> LocalizableText {
        LocalizableText(key: "", verbatim: text)
    }
}

enum LocalizationTable {
    static let supportedCodes = ["en", "de", "es", "fr", "it", "ja", "zh"]

    static func resolvedCode(preference: String) -> String {
        guard preference == "system" else {
            return supportedCodes.contains(preference) ? preference : "en"
        }
        for identifier in Locale.preferredLanguages {
            let code = languageCode(from: identifier)
            if supportedCodes.contains(code) {
                return code
            }
        }
        return "en"
    }

    static func languageName(for identifier: String, displayLanguage: String) -> String {
        let code = languageCode(from: identifier)
        let locale = Locale(identifier: displayLanguage)
        guard let name = locale.localizedString(forLanguageCode: code), !name.isEmpty else {
            return code
        }
        return name.capitalized(with: locale)
    }

    static func string(_ text: LocalizableText, languageCode: String) -> String {
        if let verbatim = text.verbatim {
            return verbatim
        }
        guard !text.key.isEmpty else { return "" }
        let code = supportedCodes.contains(languageCode) ? languageCode : "en"
        let template = catalogs[code]?[text.key] ?? text.key
        let values = text.arguments.map { argument -> String in
            switch argument {
            case .text(let value):
                return value
            case .language(let identifier):
                return languageName(for: identifier, displayLanguage: code)
            }
        }
        guard !values.isEmpty else { return template }
        return String(format: template, locale: Locale(identifier: code), arguments: values.map { $0 as CVarArg })
    }

    static func languageCode(from identifier: String) -> String {
        let normalized = identifier.replacingOccurrences(of: "_", with: "-").lowercased()
        return String(normalized.split(separator: "-").first ?? Substring(normalized))
    }

